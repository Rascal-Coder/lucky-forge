		}
		if (GuideNum == 8)
		{
		 pagearrow.SetActive(false);
		 yerArrow.gameObject.SetActive(true);
		 foreach (InventorySlot candidate in warController.slotMachine.commanderSpawner.inventorySlots)
		 {
		  if (!candidate.IsFull()) continue;
		  slot = candidate;
		  break;
		 }
		 yerArrow.transform.position = slot.transform.position;
		 yaziEkrani.SetActive(false);
		 GuideNum = 9;
		}
		if (GuideNum == 9 && craftSell.gameObject.activeInHierarchy)
		{
		 yerArrow.gameObject.SetActive(false);
		 mergeArrow.SetActive(true);
		 GuideNum = 10;
		}
		if (GuideNum == 10 && !slot.IsFull())
		{
		 WarController.StopGame = false;
		 yerArrow.gameObject.SetActive(false);
		 mergeArrow.SetActive(false);
		 GuideNum = 11;
		}
		if (GuideNum == 11 && warController.Silver >= warController.slotMachine.SpinFiyat())
		{
		 yaziver(Lang.Get.inWarGuide10);
		 warController.slotMachine.SetNextSpinPreview(new SlotMachine.Type[] {(SlotMachine.Type)0,(SlotMachine.Type)0,(SlotMachine.Type)2,(SlotMachine.Type)1,(SlotMachine.Type)0,(SlotMachine.Type)2},0,3);
		 WarController.StopGame = true;
		 spinArrow.SetActive(true);
		 GuideNum = 12;
		}
		if (GuideNum == 12 && warController.Silver < warController.slotMachine.SpinFiyat())
		{
		 warController.slotMachine.SetNextSpinPreview(new SlotMachine.Type[] {(SlotMachine.Type)0,(SlotMachine.Type)2,(SlotMachine.Type)0,(SlotMachine.Type)1,(SlotMachine.Type)0,(SlotMachine.Type)0},1,1);
		 WarController.StopGame = false;
		 yaziEkrani.SetActive(false);
		 spinArrow.SetActive(false);
		 GuideNum = 13;
		}
		if (GuideNum == 13 && warController.Silver >= warController.slotMachine.SpinFiyat())
		{
		 warController.slotMachine.SetNextSpinPreview(new SlotMachine.Type[] {(SlotMachine.Type)0,(SlotMachine.Type)2,(SlotMachine.Type)0,(SlotMachine.Type)0,(SlotMachine.Type)0,(SlotMachine.Type)0},2,1);
		 WarController.StopGame = true;
		 sonweaponadet = warController.slotMachine.commanderSpawner.activeCommanders.Count;
		 spinArrow.SetActive(true);
		 GuideNum = 14;
		}
		if (GuideNum == 14)
		{
		 if (warController.slotMachine.spining || sonweaponadet == warController.slotMachine.commanderSpawner.activeCommanders.Count) return;
		 pagearrow.SetActive(true);
		 StartCoroutine(LateOpen(Lang.Get.inWarGuide4));
		 WarController.StopGame = true;
		 spinArrow.SetActive(false);
		 GuideNum = 15;
		 return;
		}
		if (GuideNum == 16)
		{
		 pagearrow.SetActive(false);
		 if (warController.Silver >= warController.slotMachine.SpinFiyat())
		 {
		  pagearrow.SetActive(false);
		  warController.slotMachine.SetNextSpinPreview(new SlotMachine.Type[] {(SlotMachine.Type)1,(SlotMachine.Type)0,(SlotMachine.Type)2,(SlotMachine.Type)1,(SlotMachine.Type)0,(SlotMachine.Type)1},0,0);
		  yaziEkrani.SetActive(false);
		  spinArrow.SetActive(true);
		  GuideNum = 17;
		  WarController.StopGame = true;
		 }
		}
		if (GuideNum == 17 && roguleLike.gameObject.activeInHierarchy)
		{
		 spinArrow.SetActive(false);
		 GuideNum = 18;
		}
		if (GuideNum == 18 && !roguleLike.gameObject.activeInHierarchy)
		{
		 warController.AddSilver(30f);
		 yaziver(Lang.Get.inWarGuide9);
		 spinArrow.SetActive(true);
		 newgame = false;
		 warController.slotMachine.SetNextSpinPreview(new SlotMachine.Type[6],3,0);
		 GuideNum = 19;
		}
		if (GuideNum == 19 && warController.slotMachine.spining)
		{
		 warController.slotMachine.guidePreview = false;
		 WarController.StopGame = false;
		 yaziEkrani.SetActive(false);
		 spinArrow.SetActive(false);
		 newgame = false;
		 GuideNum = 20;
		}
	}
